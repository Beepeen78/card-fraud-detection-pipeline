-- Create a view for high-risk transactions
CREATE OR REPLACE VIEW FRAUD_DETECTION.PRODUCTION.HIGH_RISK_TRANSACTIONS AS
SELECT 
    TRANSACTION_ID,
    CUSTOMER_ID,
    AMOUNT,
    FRAUD_PROBABILITY,
    FRAUD_PREDICTION,
    IS_FRAUD,
    SCORE_TIME,
    CASE 
        WHEN FRAUD_PROBABILITY >= 0.8 THEN 'CRITICAL'
        WHEN FRAUD_PROBABILITY >= 0.6 THEN 'HIGH'
        WHEN FRAUD_PROBABILITY >= 0.4 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS RISK_LEVEL
FROM FRAUD_DETECTION.PRODUCTION.TRANSACTIONS_SCORED
WHERE FRAUD_PROBABILITY >= 0.4
ORDER BY FRAUD_PROBABILITY DESC;

-- Create a view for daily fraud summary
CREATE OR REPLACE VIEW FRAUD_DETECTION.PRODUCTION.DAILY_FRAUD_SUMMARY AS
SELECT 
    DATE,
    TRANSACTIONS,
    FLAGGED,
    ACTUAL_FRAUD,
    ROUND(AVG_RISK, 4) AS AVG_RISK,
    TOTAL_AMOUNT,
    ROUND((FLAGGED::FLOAT / TRANSACTIONS::FLOAT) * 100, 2) AS FLAG_RATE_PCT,
    ROUND((ACTUAL_FRAUD::FLOAT / TRANSACTIONS::FLOAT) * 100, 4) AS ACTUAL_FRAUD_RATE_PCT,
    CASE 
        WHEN ACTUAL_FRAUD > 0 THEN ROUND((FLAGGED::FLOAT / ACTUAL_FRAUD::FLOAT) * 100, 2)
        ELSE 0
    END AS RECALL_PCT
FROM FRAUD_DETECTION.PRODUCTION.METRICS_DAILY
ORDER BY DATE DESC;
