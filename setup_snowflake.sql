-- Snowflake Database and Schema Setup for Fraud Detection Pipeline
-- Run these commands in Snowflake to set up the database structure

-- Create database if it doesn't exist
CREATE DATABASE IF NOT EXISTS FRAUD_DETECTION;

-- Create schema if it doesn't exist
CREATE SCHEMA IF NOT EXISTS FRAUD_DETECTION.PRODUCTION;

-- Create transactions_scored table
CREATE TABLE IF NOT EXISTS FRAUD_DETECTION.PRODUCTION.TRANSACTIONS_SCORED (
    TRANSACTION_ID VARCHAR(255),
    CUSTOMER_ID VARCHAR(255),
    AMOUNT FLOAT,
    FRAUD_PROBABILITY FLOAT,
    FRAUD_PREDICTION INTEGER,
    IS_FRAUD INTEGER,
    SCORE_TIME TIMESTAMP_NTZ,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Create metrics_daily table
CREATE TABLE IF NOT EXISTS FRAUD_DETECTION.PRODUCTION.METRICS_DAILY (
    DATE DATE,
    TRANSACTIONS INTEGER,
    FLAGGED INTEGER,
    AVG_RISK FLOAT,
    TOTAL_AMOUNT FLOAT,
    ACTUAL_FRAUD INTEGER,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS IDX_TRANSACTIONS_CUSTOMER_ID 
ON FRAUD_DETECTION.PRODUCTION.TRANSACTIONS_SCORED (CUSTOMER_ID);

CREATE INDEX IF NOT EXISTS IDX_TRANSACTIONS_SCORE_TIME 
ON FRAUD_DETECTION.PRODUCTION.TRANSACTIONS_SCORED (SCORE_TIME);

CREATE INDEX IF NOT EXISTS IDX_TRANSACTIONS_FRAUD_PREDICTION 
ON FRAUD_DETECTION.PRODUCTION.TRANSACTIONS_SCORED (FRAUD_PREDICTION);

CREATE INDEX IF NOT EXISTS IDX_METRICS_DATE 
ON FRAUD_DETECTION.PRODUCTION.METRICS_DAILY (DATE);

